/**
 * 전시가 끝난 뒤에도 "우리의 우주"를 다시 볼 수 있는 실제 공개 주소.
 *
 * ─── 지금은 없다. 지어내지 않는다 ───────────────────────
 *  확인해 보니 이 프로젝트에는 아직 두 가지가 다 없다.
 *
 *   1. 외부에 공개된 배포 주소 — `vite.config.ts`가 상대 경로(`base: './'`)로
 *      굽는 것도, 전시장 태블릿에 그대로 얹는다는 뜻이다. Vercel·Netlify
 *      같은 배포 설정이나 `.env`, `package.json`의 `homepage` 어디에도
 *      공개 주소가 없다.
 *   2. 모두가 같은 우주를 보게 할 공유 저장소 — `data/universeRepository.ts`의
 *      `createLocalUniverse`는 **이 브라우저의 localStorage만** 본다
 *      (`src/data/index.ts`에 "허브(서버)를 붙일 때 바꾸는 곳은 이 한
 *      줄"이라고 적혀 있지만, 그 허브 쪽 저장소는 아직 없다).
 *
 *  둘 다 없는 채로 QR코드를 찍으면, 스캔한 사람의 화면에는 아무것도
 *  뜨지 않거나(주소가 없음) 자기 혼자만의 빈 우주가 뜬다(공유 저장소가
 *  없음) — 둘 다 "다시 볼 수 있다"는 말을 거짓으로 만든다.
 *
 *  그래서 기본값은 `null`이다. `Receipt`는 이 값이 있을 때만 두 번째
 *  QR코드를 그린다 — 없는 주소를 찍어 내는 일은 없다.
 * ───────────────────────────────────────────────────────
 *
 * ─── 실제로 켜려면 ──────────────────────────────────────
 *  1. 공동 우주를 공개 인터넷에서 볼 수 있는 실제 주소로 배포한다.
 *  2. 그 배포가 **이 전시장 브라우저의 localStorage가 아니라, 모두가
 *     보는 공유 저장소**(허브 서버 등)를 읽도록 한다 — 1번만 하고
 *     2번을 안 하면, 그 주소를 열어도 "우리의 우주"가 아니라 빈
 *     우주만 보인다.
 *  3. 그 뒤에는 이 값을 코드에서 바꾸지 않는다 — 배포 환경(Vercel 등)의
 *     환경변수 `VITE_PUBLIC_UNIVERSE_URL`에 실제 주소를 적는다. 그
 *     환경변수가 없는 빌드(지금의 전시장 키오스크 빌드가 그렇다)는
 *     계속 `null`이다 — 없는 주소를 지어내 붙이지 않는다.
 *
 *  `import.meta.env`는 Vite가 굽는 브라우저 빌드에만 있다 — `scripts/check.mjs`는
 *  이 파일을 Vite 없이 rolldown+node로 돌리므로 `env` 자체가 없다.
 *  그래서 `?.`로 없는 경우를 안전하게 지나간다(없으면 `null`).
 */
export const PUBLIC_UNIVERSE_URL: string | null = import.meta.env?.VITE_PUBLIC_UNIVERSE_URL || null
